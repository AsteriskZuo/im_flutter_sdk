import 'dart:convert';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

import '../tool/env_tool.dart';

const _configTemplate = '''
{
  "restApi": "https://example.invalid",
  "appKey": "org#app",
  "clientId": "client-id",
  "clientSecret": "client-secret",
  "accounts": [{"id": "user01"}],
  "chatOptions": {"debugMode": true, "autoLoadConversations": true}
}
''';

const _envTemplate = 'const Map<String, Object?> environment = '
    '<String, Object?>{};\n';

Directory _createExampleFixture() {
  final root = Directory.systemTemp.createTempSync('env_tool_test_');
  Directory('${root.path}/templates').createSync(recursive: true);
  File('${root.path}/templates/config.local.example.json')
      .writeAsStringSync(_configTemplate);
  File('${root.path}/templates/env.example.dart')
      .writeAsStringSync(_envTemplate);
  return root;
}

void main() {
  test('ensureLocalFiles copies both templates and is idempotent', () async {
    final root = _createExampleFixture();
    addTearDown(() => root.deleteSync(recursive: true));
    final paths = EnvPaths(root);

    await ensureLocalFiles(paths);
    expect(paths.localConfig.existsSync(), isTrue);
    expect(paths.activeEnv.existsSync(), isTrue);
    expect(paths.localConfig.readAsStringSync(), _configTemplate);
    expect(paths.activeEnv.readAsStringSync(), _envTemplate);
    if (!Platform.isWindows) {
      final mode = paths.activeEnv.statSync().mode & 0x1FF;
      expect(mode, 0x180, reason: 'env.dart must be owner read/write only');
    }

    paths.localConfig.writeAsStringSync('{"keep": true}');
    await ensureLocalFiles(paths);
    expect(paths.localConfig.readAsStringSync(), '{"keep": true}');
  });

  test('generateEnvironment fails before any network call without credentials',
      () async {
    final root = _createExampleFixture();
    addTearDown(() => root.deleteSync(recursive: true));
    final paths = EnvPaths(root);
    await ensureLocalFiles(paths);
    paths.localConfig.writeAsStringSync(jsonEncode({
      'restApi': 'https://example.invalid',
      'appKey': 'org#app',
      'accounts': [
        {'id': 'user01'}
      ],
    }));

    await expectLater(
      generateEnvironment(paths),
      throwsA(isA<FormatException>().having(
        (error) => error.message,
        'message',
        contains('clientId'),
      )),
    );
    expect(paths.activeEnv.readAsStringSync(), _envTemplate);
  });

  test('generateEnvironment rejects the removed multi-cluster shape', () async {
    final root = _createExampleFixture();
    addTearDown(() => root.deleteSync(recursive: true));
    final paths = EnvPaths(root);
    await ensureLocalFiles(paths);
    paths.localConfig.writeAsStringSync(jsonEncode({
      'clusters': <Object?>[],
      'defaultCluster': 'local',
    }));

    await expectLater(
      generateEnvironment(paths),
      throwsA(isA<FormatException>().having(
        (error) => error.message,
        'message',
        contains('multi-cluster'),
      )),
    );
  });

  test('renderEnvironmentDart writes typed literals and escapes dollars', () {
    final rendered = renderEnvironmentDart(<String, Object?>{
      'appKey': 'org#app',
      'nickname': r'$nick',
      'accounts': <Object?>[
        <String, Object?>{'id': 'user01', 'token': r'$token'},
      ],
      'groups': <Object?>[],
      'ext': <String, Object?>{},
      'debugMode': true,
    });

    expect(rendered, startsWith('// Generated by tool/env_tool.dart'));
    expect(rendered, contains('const Map<String, Object?> environment ='));
    expect(rendered, contains(r'\$nick'));
    expect(rendered, contains(r'\$token'));
    expect(rendered, contains('<Object?>[]'));
    expect(rendered, contains('<String, Object?>{}'));
    expect(rendered, contains('"debugMode": true'));
  });

  test('buildEnvironment merges chat options and drops legacy cluster fields',
      () {
    final environment = buildEnvironment(
      config: <String, dynamic>{
        'appKey': 'org#app',
        'chatOptions': <String, dynamic>{
          'debugMode': true,
          'autoLoadConversations': false,
        },
        'groups': <Object?>[
          <String, Object?>{'id': 'group01', 'cluster': 'legacy'},
        ],
        'rooms': <Object?>[],
      },
      accounts: <Map<String, Object?>>[
        <String, Object?>{'id': 'user01', 'token': 'token01'},
      ],
    );

    expect(environment['appKey'], 'org#app');
    expect(environment['debugMode'], isTrue);
    expect(environment['autoLoadConversations'], isFalse);
    expect(environment['accounts'], hasLength(1));
    expect(environment['groups'], <Object?>[
      <String, Object?>{'id': 'group01'},
    ]);
    expect(environment['rooms'], isEmpty);
    expect(environment['enablePrivateConfig'], isNull);
  });

  test('buildEnvironment enforces private config servers', () {
    final config = <String, dynamic>{
      'appKey': 'org#app',
      'enablePrivateConfig': true,
      'webSocketServer': 'ws.example.invalid',
      'restServer': 'rest.example.invalid',
      'imServer': 'im.example.invalid',
      'imPort': 443,
      'webSocketPort': 0,
    };

    final environment = buildEnvironment(config: config, accounts: const []);

    expect(environment['enableDNSConfig'], isFalse);
    expect(environment['webSocketServer'], 'ws.example.invalid');
    expect(environment['restServer'], 'rest.example.invalid');
    expect(environment['imServer'], 'im.example.invalid');
    expect(environment['imPort'], 443);
    expect(environment.containsKey('webSocketPort'), isFalse);

    final broken = Map<String, dynamic>.from(config)
      ..remove('restServer')
      ..['imServer'] = 'TODO';
    expect(
      () => buildEnvironment(config: broken, accounts: const []),
      throwsA(isA<FormatException>().having(
        (error) => error.message,
        'message',
        contains('restServer'),
      )),
    );
  });

  test('buildE2eConfig maps the first account onto the six dart-defines', () {
    final result = buildE2eConfig(
      config: <String, dynamic>{
        'restApi': 'https://rest.example.invalid',
        'appKey': 'org#app',
      },
      accounts: const [
        <String, Object?>{'id': 'user01', 'token': 'user-token'},
        <String, Object?>{'id': 'user02', 'token': 'other-token'},
      ],
      appToken: 'app-token',
    );

    expect(result, <String, String>{
      'E2E_APP_KEY': 'org#app',
      'E2E_USER_ID': 'user01',
      'E2E_USER_TOKEN': 'user-token',
      'E2E_PEER_ID': 'user01_ci_peer',
      'E2E_REST_API': 'https://rest.example.invalid',
      'E2E_APP_TOKEN': 'app-token',
    });
  });

  test('writeE2eConfig asks for config.local.json before any network call',
      () async {
    final root = _createExampleFixture();
    addTearDown(() => root.deleteSync(recursive: true));

    await expectLater(
      writeE2eConfig(EnvPaths(root), const []),
      throwsA(isA<FormatException>().having(
        (error) => error.message,
        'message',
        contains('config.local.json'),
      )),
    );
  });

  test('parseE2eConfigOptions accepts the five long-lived values only', () {
    final parsed = parseE2eConfigOptions(const [
      '--output',
      '/tmp/out.json',
      '--app-key',
      'org#app',
      '--user-id',
      'user01',
      '--rest-api',
      'https://rest.example.invalid',
      '--client-id',
      'client-id',
      '--client-secret',
      'client-secret',
    ]);

    expect(parsed.output, '/tmp/out.json');
    expect(parsed.hasCredentials, isTrue);
    expect(parsed.toConfig(), <String, dynamic>{
      'restApi': 'https://rest.example.invalid',
      'appKey': 'org#app',
      'clientId': 'client-id',
      'clientSecret': 'client-secret',
      'accounts': <Map<String, Object?>>[
        <String, Object?>{'id': 'user01'},
      ],
    });
  });

  test('parseE2eConfigOptions rejects partial credentials', () {
    final parsed = parseE2eConfigOptions(const [
      '--app-key',
      'org#app',
    ]);

    expect(
      parsed.toConfig,
      throwsA(isA<FormatException>().having(
        (error) => error.message,
        'message',
        allOf(contains('missing'), contains('userId')),
      )),
    );
  });
}
